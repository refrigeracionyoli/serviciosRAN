do $$
begin
  if exists (
    select 1
    from pg_publication
    where pubname = 'supabase_realtime'
  ) then
    if not exists (
      select 1
      from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = 'servicios'
    ) then
      alter publication supabase_realtime add table public.servicios;
    end if;

    if not exists (
      select 1
      from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = 'evidencias'
    ) then
      alter publication supabase_realtime add table public.evidencias;
    end if;
  end if;
end $$;
